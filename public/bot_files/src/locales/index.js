function resolveDynamicCountryKey(lang, key) {
  if (!key.startsWith("grizzly_country_")) {
    return null;
  }
  const id = key.replace("grizzly_country_", "");
  const country = getGrizzlyCountryMeta(id);
  if (!country) {
    return null;
  }
  if (lang === "en") {
    return country.name_en || country.name_ar || null;
  }
  return country.name_ar || country.name_en || null;
}

function t(lang, key) {
  const selectedLang = locales[lang] ? lang : "ar";
  const value = locales[selectedLang][key];
  if (typeof value === "string") {
    return value;
  }

  const dynamicCountry = resolveDynamicCountryKey(selectedLang, key);
  if (dynamicCountry) {
    return dynamicCountry;
  }

  return locales.ar[key] || key;
}

function getUserLang(user) {
  return user?.language === "en" ? "en" : "ar";
}

function getArray(lang, key) {
  const selectedLang = locales[lang] ? lang : "ar";
  if (Array.isArray(locales[selectedLang][key])) {
    return locales[selectedLang][key];
  }
  return Array.isArray(locales.ar[key]) ? locales.ar[key] : [];
}

